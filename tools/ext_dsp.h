// Adapters exposing the non-Faust engines (Cmajor generated C++, Cmajor JIT, YUP YDSP JIT) through the
// Faust `dsp` interface, so the harness measures them with the same loop as the Faust engines.
#pragma once
#include <cstdio>
#include <cstdlib>
#include <string>

#include <faust/dsp/dsp.h>
#include <faust/gui/UI.h>
#include <faust/gui/meta.h>

struct ext_dsp : public dsp {
    int fNumInputs = 0, fNumOutputs = 0, fSampleRate = 0;
    int getNumInputs() override { return fNumInputs; }
    int getNumOutputs() override { return fNumOutputs; }
    void buildUserInterface(UI*) override {}
    int getSampleRate() override { return fSampleRate; }
    void init(int sr) override { instanceInit(sr); }
    void instanceInit(int sr) override {
        fSampleRate = sr;
        instanceConstants(sr);
        instanceResetUserInterface();
        instanceClear();
    }
    void instanceConstants(int) override {}
    void instanceResetUserInterface() override {}
    dsp* clone() override { return nullptr; }
    void metadata(Meta*) override {}
};

// C++ class generated by `cmaj generate --target=cpp` (renamed P by build.sh). Streams are named in1.. and out1..
// The class only exchanges audio through copies: setInputFrames before advance(), copyOutputFrames after.
template <class P>
struct cmaj_cpp_dsp : public ext_dsp {
    P* fProc = new P();
    typename P::EndpointHandle fIn[16], fOut[16];
    cmaj_cpp_dsp() {
        for (int c = 0; c < 16; c++) {
            fIn[c] = P::getEndpointHandleForName("in" + std::to_string(c + 1));
            fOut[c] = P::getEndpointHandleForName("out" + std::to_string(c + 1));
            if (fIn[c] && c == fNumInputs) fNumInputs++;
            if (fOut[c] && c == fNumOutputs) fNumOutputs++;
        }
    }
    ~cmaj_cpp_dsp() override { delete fProc; }
    void instanceClear() override { fProc->initialise(0, (double)fSampleRate); }
    void compute(int count, FAUSTFLOAT** in, FAUSTFLOAT** out) override {
        for (int c = 0; c < fNumInputs; c++) fProc->setInputFrames(fIn[c], in[c], (uint32_t)count, 0);
        fProc->advance(count);
        for (int c = 0; c < fNumOutputs; c++) fProc->copyOutputFrames(fOut[c], out[c], (uint32_t)count);
    }
};

// A runtime-compiled engine behind a C interface (tools/cmaj_jit.h, tools/ydsp/ydsp_engine.h).
struct c_api_dsp : public ext_dsp {
    void* fEngine;
    void (*fReset)(void*);
    void (*fProcess)(void*, float* const*, float* const*, int);
    void (*fDestroy)(void*);
    c_api_dsp(void* e, int nin, int nout, void (*r)(void*), void (*p)(void*, float* const*, float* const*, int),
              void (*d)(void*))
        : fEngine(e), fReset(r), fProcess(p), fDestroy(d) {
        fNumInputs = nin;
        fNumOutputs = nout;
    }
    ~c_api_dsp() override { fDestroy(fEngine); }
    void instanceClear() override { fReset(fEngine); }
    void compute(int count, FAUSTFLOAT** in, FAUSTFLOAT** out) override { fProcess(fEngine, in, out, count); }
};
